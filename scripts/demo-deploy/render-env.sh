SANDBOX_SERVICE_KEY=${SANDBOX_SERVICE_KEY}
SANDBOX_HOST_PORT=${SANDBOX_HOST_PORT}
MBOS_ENDPOINT_PROXY_DEFAULT_TIMEOUT_SECONDS=${MBOS_ENDPOINT_PROXY_DEFAULT_TIMEOUT_SECONDS:-120}
MBOS_UNIVERSAL_PROXY_BASE_URL=${COMPOSE_INTERNAL_UNIVERSAL_PROXY_BASE_URL}
EOF

cat > "${RELEASE_ROOT}/env/web.env" <<EOF
